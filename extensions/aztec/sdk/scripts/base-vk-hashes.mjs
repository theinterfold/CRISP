// Prints the hashes of the `noir-recursive-no-zk` verification keys of the two base circuits of a BFV preset, the
// `encryption_vk_hash` and `crisp_vk_hash` that `crisp_aztec` is deployed with:
//
//   pnpm base-vk-hashes insecure-64     (or secure-8192)
//
// Unlike the fold's, they depend on the preset. The script compiles the CRISP circuits for the preset
// (`scripts/compile_circuits.sh`, which leaves `circuits/bin/crisp/target/crisp.vk_recursive_hash`) and reads the
// `user_data_encryption` hash from the pinned Interfold release (`scripts/interfold-release.mjs circuits`), the same two
// files `scripts/compute_vk_hash.sh` binds in the fold.
//
// With `--fixture <file>` it also writes the Noir fixture of the TXE tests (`crisp_aztec_test/src/base_fixture.nr`):
// the two keys and their hashes, from `bb write_vk` of the same circuits.
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

const [preset, flag, fixturePath] = process.argv.slice(2)
if (!preset || (flag !== undefined && (flag !== '--fixture' || !fixturePath))) {
  console.error('usage: pnpm base-vk-hashes <preset> [--fixture <file>]   (preset: insecure-64 or secure-8192)')
  process.exit(1)
}

const root = resolve(import.meta.dirname, '../../../..')
const run = (command, args) => execFileSync(command, args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] })

// Compile output goes to stderr so stdout stays the JSON below.
execFileSync('bash', ['scripts/compile_circuits.sh', preset], { cwd: root, stdio: ['ignore', 2, 2] })
const interfold = run('node', ['scripts/interfold-release.mjs', 'circuits']).trim()

const hex = (bytes) => `0x${Buffer.from(bytes).toString('hex')}`
const encryptionCircuit = join(interfold, preset, 'user_data_encryption.json')
const crispCircuit = join(root, 'circuits/bin/crisp/target/crisp.json')
const hashes = {
  encryption: hex(readFileSync(join(interfold, preset, 'user_data_encryption.vk_recursive_hash'))),
  crisp: hex(readFileSync(join(root, 'circuits/bin/crisp/target/crisp.vk_recursive_hash'))),
}
console.log(JSON.stringify(hashes, null, 2))

if (fixturePath) {
  const scratch = mkdtempSync(join(tmpdir(), 'base-vk-'))
  try {
    const keyOf = (circuit, name) => {
      const out = join(scratch, name)
      execFileSync('bb', ['write_vk', '-b', circuit, '-o', out, '-t', 'noir-recursive-no-zk'], { stdio: ['ignore', 2, 2] })
      const vk = readFileSync(join(out, 'vk'))
      return {
        hash: hex(readFileSync(join(out, 'vk_hash'))),
        fields: Array.from({ length: vk.length / 32 }, (_, i) => hex(vk.subarray(i * 32, (i + 1) * 32))),
      }
    }
    const keys = { encryption: keyOf(encryptionCircuit, 'encryption'), crisp: keyOf(crispCircuit, 'crisp') }
    for (const name of ['encryption', 'crisp']) {
      if (keys[name].hash !== hashes[name]) throw new Error(`bb write_vk gave another ${name} key hash than the one the circuits ship`)
      if (keys[name].fields.length !== 115) throw new Error(`The ${name} key has ${keys[name].fields.length} fields, expected 115`)
    }

    const block = (name) => {
      const upper = name.toUpperCase()
      return `pub global ${upper}_VK_HASH: Field = ${keys[name].hash};\n\npub global ${upper}_VK: [Field; 115] = [\n${keys[name].fields.map((field) => `    ${field},`).join('\n')}\n];\n`
    }
    const header = `// The verification keys of the two base circuits of the \`${preset}\` preset, for the \`noir-recursive-no-zk\` target, and
// their Poseidon2 hashes. TXE does not execute proof verification, so tests exercise the hash checks and the links
// between the proofs with these keys; real proofs are verified on a local network (see the README).
// Generated by \`pnpm base-vk-hashes ${preset} --fixture <this file>\` in \`extensions/aztec/sdk\`; do not edit.
`
    writeFileSync(resolve(fixturePath), `${header}${block('encryption')}\n${block('crisp')}`)
  } finally {
    rmSync(scratch, { recursive: true, force: true })
  }
}
