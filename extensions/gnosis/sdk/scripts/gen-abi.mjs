// Regenerates src/abi/*.ts from the ABI files the contracts project commits (`../contracts/abi/<Name>.json`, plain ABI arrays).
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const names = ['CrispGnosisVoting', 'CRISPGnosisProgram', 'CrispGovernanceModule', 'CrispDemoToken', 'MockAMB']
const header = `// SPDX-License-Identifier: LGPL-3.0-only
//
// This file is provided WITHOUT ANY WARRANTY;
// without even the implied warranty of MERCHANTABILITY
// or FITNESS FOR A PARTICULAR PURPOSE.

// Generated by \`pnpm gen:abi\` from extensions/gnosis/contracts/abi/. Do not edit.
`
const lowerFirst = (name) => name.replace(/^[A-Z]+(?=[A-Z][a-z])|^[A-Z]/, (head) => head.toLowerCase())

for (const name of names) {
  const abi = JSON.parse(readFileSync(new URL(`../../contracts/abi/${name}.json`, import.meta.url), 'utf8'))
  const out = join(new URL('../src/abi/', import.meta.url).pathname, `${name}.ts`)
  writeFileSync(out, `${header}\nexport const ${lowerFirst(name)}Abi = ${JSON.stringify(abi, null, 2)} as const\n`)
  console.log(`wrote ${out}`)
}
